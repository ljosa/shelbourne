#!/usr/bin/env python3
"""
Generate anti-aliased bitmap font data from DejaVu Sans for the
Shelbourne 128x100 grayscale OLED display.

Outputs:
  fonts.h      — C header with glyph data for three sizes
  fonts/*.png  — preview images of each size

Sizes:
  small  — ~10px height, for labels (track index, volume)
  medium — ~16px height, for station names, metadata
  large  — ~28px height, for the clock display
"""

import os
import struct
from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/tmp/dejavu/dejavu-fonts-ttf-2.37/ttf/DejaVuSans.ttf"
FONT_BOLD_PATH = "/tmp/dejavu/dejavu-fonts-ttf-2.37/ttf/DejaVuSans-Bold.ttf"

# ASCII 32-126
FIRST_CHAR = 32
LAST_CHAR = 126
NUM_CHARS = LAST_CHAR - FIRST_CHAR + 1

# Display dimensions
FB_W = 128
FB_H = 100

# Font sizes to generate (Pillow point sizes, tuned empirically)
SIZES = {
    "small":  {"pt": 11, "path": FONT_PATH},
    "medium": {"pt": 16, "path": FONT_PATH},
    "large":  {"pt": 28, "path": FONT_BOLD_PATH},
}


def render_font(name, pt, font_path):
    """Render all printable ASCII glyphs, return (height, widths[], data[])."""
    font = ImageFont.truetype(font_path, pt)

    # First pass: measure all glyphs to find max height and individual widths
    widths = []
    bboxes = []
    max_ascent = 0
    max_descent = 0

    for ch in range(FIRST_CHAR, LAST_CHAR + 1):
        c = chr(ch)
        bbox = font.getbbox(c)  # (left, top, right, bottom)
        left, top, right, bottom = bbox
        w = right - left
        # Use advance width for consistent spacing
        adv = font.getlength(c)
        w = int(round(adv))
        if w < 1:
            w = 1
        widths.append(w)
        bboxes.append(bbox)
        if -top > max_ascent:
            max_ascent = -top
        if bottom > max_descent:
            max_descent = bottom

    # Measure using getmetrics for consistent baseline
    ascent, descent = font.getmetrics()
    height = ascent + descent

    # Second pass: render each glyph
    all_data = []
    for i, ch in enumerate(range(FIRST_CHAR, LAST_CHAR + 1)):
        c = chr(ch)
        w = widths[i]
        img = Image.new("L", (w, height), 0)
        draw = ImageDraw.Draw(img)
        draw.text((0, 0), c, fill=255, font=font)
        pixels = list(img.getdata())
        all_data.append(pixels)

    return height, widths, all_data


def generate_preview(name, height, widths, all_data):
    """Generate a PNG preview of the font."""
    os.makedirs("fonts", exist_ok=True)

    # Arrange glyphs in rows
    margin = 2
    x, y = margin, margin
    row_height = height + margin
    img = Image.new("L", (FB_W * 4, row_height * 12), 0)

    for i, ch in enumerate(range(FIRST_CHAR, LAST_CHAR + 1)):
        w = widths[i]
        if x + w + margin > img.width:
            x = margin
            y += row_height
        glyph_img = Image.new("L", (w, height))
        glyph_img.putdata(all_data[i])
        img.paste(glyph_img, (x, y))
        x += w + margin

    # Crop to content
    bbox = img.getbbox()
    if bbox:
        img = img.crop((0, 0, bbox[2] + margin, bbox[3] + margin))
    img.save(f"fonts/font_{name}.png")

    # Also render sample text on a 128x100 "screen"
    screen = Image.new("L", (FB_W, FB_H), 0)
    if name == "large":
        text = "4:56"
    elif name == "medium":
        text = "Eye on Sky"
    else:
        text = "1/42  Vol:75"

    # Center the text
    total_w = sum(widths[ord(c) - FIRST_CHAR] for c in text if FIRST_CHAR <= ord(c) <= LAST_CHAR)
    sx = (FB_W - total_w) // 2
    sy = (FB_H - height) // 2

    for c in text:
        idx = ord(c) - FIRST_CHAR
        if idx < 0 or idx >= NUM_CHARS:
            continue
        w = widths[idx]
        glyph_img = Image.new("L", (w, height))
        glyph_img.putdata(all_data[idx])
        if 0 <= sx < FB_W and 0 <= sy < FB_H:
            screen.paste(glyph_img, (sx, sy))
        sx += w

    screen.save(f"fonts/screen_{name}.png")
    print(f"  Preview: fonts/font_{name}.png, fonts/screen_{name}.png")


def generate_header(sizes_data):
    """Generate fonts.h C header."""
    lines = []
    lines.append("/* fonts.h — generated by gen_fonts.py, do not edit */")
    lines.append("#ifndef FONTS_H")
    lines.append("#define FONTS_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    uint8_t height;")
    lines.append("    const uint8_t widths[95];    /* ASCII 32-126 */")
    lines.append("    const uint16_t offsets[95];  /* byte offset into data[] */")
    lines.append("    const uint8_t *data;")
    lines.append("} font_t;")
    lines.append("")

    for name, (height, widths, all_data) in sizes_data.items():
        # Build contiguous data array and offset table
        data_bytes = []
        offsets = []
        for i in range(NUM_CHARS):
            offsets.append(len(data_bytes))
            data_bytes.extend(all_data[i])

        # Emit data array
        lines.append(f"static const uint8_t font_{name}_data[] = {{")
        for i in range(0, len(data_bytes), 16):
            chunk = data_bytes[i:i+16]
            hex_vals = ",".join(f"0x{b:02x}" for b in chunk)
            lines.append(f"    {hex_vals},")
        lines.append("};")
        lines.append("")

        # Emit font struct
        w_str = ",".join(str(w) for w in widths)
        o_str = ",".join(str(o) for o in offsets)
        lines.append(f"static const font_t font_{name} = {{")
        lines.append(f"    .height = {height},")
        lines.append(f"    .widths = {{{w_str}}},")
        lines.append(f"    .offsets = {{{o_str}}},")
        lines.append(f"    .data = font_{name}_data,")
        lines.append("};")
        lines.append("")

    lines.append("#endif /* FONTS_H */")
    lines.append("")

    with open("fonts.h", "w") as f:
        f.write("\n".join(lines))
    print(f"Generated fonts.h ({len(lines)} lines)")


def main():
    sizes_data = {}
    for name, cfg in SIZES.items():
        print(f"Rendering {name} ({cfg['pt']}pt)...")
        height, widths, all_data = render_font(name, cfg["pt"], cfg["path"])
        print(f"  Height: {height}px, widths: {min(widths)}-{max(widths)}px")

        # For "large" (clock), make digits 0-9 tabular (same width)
        if name == "large":
            digit_widths = [widths[ord(c) - FIRST_CHAR] for c in "0123456789"]
            max_digit_w = max(digit_widths)
            for c in "0123456789":
                idx = ord(c) - FIRST_CHAR
                old_w = widths[idx]
                if old_w < max_digit_w:
                    # Pad glyph data: center the glyph in the wider cell
                    pad_left = (max_digit_w - old_w) // 2
                    pad_right = max_digit_w - old_w - pad_left
                    old_data = all_data[idx]
                    new_data = []
                    for row in range(height):
                        row_start = row * old_w
                        row_pixels = old_data[row_start:row_start + old_w]
                        new_data.extend([0] * pad_left)
                        new_data.extend(row_pixels)
                        new_data.extend([0] * pad_right)
                    all_data[idx] = new_data
                    widths[idx] = max_digit_w

        sizes_data[name] = (height, widths, all_data)
        generate_preview(name, height, widths, all_data)

    generate_header(sizes_data)

    # Generate composite clock screen preview
    generate_clock_preview(sizes_data)


def render_text(screen, text, y, height, widths, all_data, center=True):
    """Render text onto a screen image. Returns x after last char."""
    total_w = sum(widths[ord(c) - FIRST_CHAR] for c in text
                  if FIRST_CHAR <= ord(c) <= LAST_CHAR)
    sx = (FB_W - total_w) // 2 if center else 0
    for c in text:
        idx = ord(c) - FIRST_CHAR
        if idx < 0 or idx >= NUM_CHARS:
            continue
        w = widths[idx]
        glyph_img = Image.new("L", (w, height))
        glyph_img.putdata(all_data[idx])
        if 0 <= sx < FB_W and 0 <= y < FB_H:
            screen.paste(glyph_img, (sx, y))
        sx += w
    return sx


def generate_clock_preview(sizes_data):
    """Render a full clock screen: large time + medium date."""
    lh, lw, ld = sizes_data["large"]
    mh, mw, md = sizes_data["medium"]

    screen = Image.new("L", (FB_W, FB_H), 0)

    # Clock centered vertically with date below
    gap = 4
    total_h = lh + gap + mh
    clock_y = (FB_H - total_h) // 2
    date_y = clock_y + lh + gap

    render_text(screen, "4:56", clock_y, lh, lw, ld)
    render_text(screen, "Thu Mar 13", date_y, mh, mw, md)

    screen.save("fonts/screen_clock.png")
    print("  Composite: fonts/screen_clock.png")


if __name__ == "__main__":
    os.chdir(os.path.dirname(os.path.abspath(__file__)))
    main()
