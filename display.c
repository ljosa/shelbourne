            uint8_t val = (bits & (1 << row)) ? 0xFF : 0x00;
            for (int dy = 0; dy < 4; dy++)
                for (int dx = 0; dx < 4; dx++) {
                    int px = x + col * 4 + dx, py = y + row * 4 + dy;
                    if (px >= 0 && px < SHELBOURNE_FB_WIDTH &&
                        py >= 0 && py < SHELBOURNE_FB_HEIGHT)
                        fb[py * SHELBOURNE_FB_WIDTH + px] = val;
                }
